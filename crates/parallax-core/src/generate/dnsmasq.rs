//! The domain-scoped DNS shim.
//!
//! The shim holds zero records. It forwards only the operator's zones to the
//! real home resolvers and rewrites their answers from real to virtual space
//! with `alias=`, which is the DNS mirror image of the NETMAP rule and comes
//! from the same [`crate::model::Network`] mapping. A catch-all public
//! resolver is added only when some template uses tunnel-wide DNS.
//!
//! Never emit a forward-everything-with-alias configuration: it would rewrite
//! answers that refer to the client's *local* network and mis-route them.

use std::fmt::Write as _;

use super::{Artifact, ArtifactKind};
use crate::validate::Model;
use crate::Result;

pub const PATH: &str = "dnsmasq/parallax.conf";

pub fn render(model: &Model<'_>) -> Result<Artifact> {
    let cfg = model.config();
    let dns = &model.server().dns;
    let mut s = String::new();
    s.push_str("# Generated by Parallax. Do not edit.\n");
    s.push_str(
        "# Domain-scoped shim: forwards only the home zones to the home resolvers and rewrites\n",
    );
    s.push_str(
        "# their A answers from real to virtual prefixes. AAAA answers pass through untranslated\n",
    );
    s.push_str("# (no IPv6 mapping in this release); PTR queries for virtual addresses are not rewritten.\n\n");
    s.push_str("no-resolv\nno-hosts\nno-poll\n");
    s.push_str("bind-dynamic\n");
    let _ = writeln!(s, "listen-address={}", model.shim_address());
    let _ = writeln!(s, "port={}", dns.port);
    s.push_str("cache-size=1000\n\n");

    s.push_str(
        "# Home zones -> the existing source of truth (only these zones transit the shim)\n",
    );
    let zones = model.zones();
    for (zone, network) in &zones {
        for upstream in &network.upstream_dns {
            let _ = writeln!(s, "server=/{zone}/{upstream}");
        }
    }
    s.push('\n');

    s.push_str(
        "# Prefix rewrite of answers, one line per mapped network (mirror of the NETMAP rule)\n",
    );
    for n in &cfg.networks {
        if let Some(m) = n.mapping() {
            let _ = writeln!(
                s,
                "alias={},{},{}",
                m.real().network(),
                m.virt().network(),
                m.netmask()
            );
        }
    }
    s.push('\n');

    s.push_str("# Rebind protection: private answers are only acceptable from the home zones\n");
    s.push_str("stop-dns-rebind\nrebind-localhost-ok\n");
    for (zone, _) in &zones {
        let _ = writeln!(s, "rebind-domain-ok=/{zone}/");
    }

    if model.needs_catch_all_resolver() {
        s.push('\n');
        s.push_str("# Catch-all for tunnel-wide clients (mobile WireGuard apps cannot split DNS, so their\n");
        s.push_str("# exports send every query here, even under a split template)\n");
        let _ = writeln!(s, "server={}", dns.public_resolver);
    } else {
        s.push('\n');
        s.push_str(
            "# No catch-all resolver: no WireGuard client is configured to use this shim, and\n",
        );
        s.push_str("# Tailscale clients split DNS natively, so queries outside the home zones never arrive.\n");
    }
    Ok(Artifact::public(ArtifactKind::Dnsmasq, PATH, s))
}
