//! The gateway's WireGuard interface config in `wg(8)` format (not
//! wg-quick): `wg syncconf` consumes it directly, and no PostUp/PostDown hooks
//! exist because the firewall is a separate, complete nftables table.

use std::fmt::Write as _;

use super::{Artifact, ArtifactKind};
use crate::io::FileSystem;
use crate::model::TransportKind;
use crate::secret::PrivateKey;
use crate::validate::Model;
use crate::{Error, Result};

pub fn path(model: &Model<'_>) -> String {
    format!("wireguard/{}.conf", model.server().wireguard.interface)
}

/// Read and check the server private key from `server.wireguard.private_key_file`.
pub fn server_private_key(model: &Model<'_>, fs: &dyn FileSystem) -> Result<PrivateKey> {
    let wg = &model.server().wireguard;
    let text = fs
        .read(&wg.private_key_file)?
        .ok_or_else(|| Error::Malformed {
            what: "server private key",
            detail: format!(
                "{} does not exist; run `parallax keygen` to create it and record its public key",
                wg.private_key_file.display()
            ),
        })?;
    let key: PrivateKey = text.trim().parse()?;
    if key.public_key() != wg.public_key {
        return Err(Error::Malformed {
            what: "server private key",
            detail: format!(
                "{} does not match server.wireguard.public_key (expected {}, file yields {})",
                wg.private_key_file.display(),
                wg.public_key,
                key.public_key()
            ),
        });
    }
    Ok(key)
}

pub fn render(model: &Model<'_>, fs: &dyn FileSystem) -> Result<Artifact> {
    let key = server_private_key(model, fs)?;
    let wg = &model.server().wireguard;
    let mut s = String::new();
    s.push_str("# Generated by Parallax. Do not edit. wg(8) format for `wg syncconf`.\n");
    s.push_str("[Interface]\n");
    let _ = writeln!(s, "PrivateKey = {}", key.expose_base64());
    let _ = writeln!(s, "ListenPort = {}", wg.listen_port);
    for peer in model.peers_on(TransportKind::WireGuard, None) {
        let Some(w) = &peer.wireguard else { continue };
        let Some(addr) = w.address else { continue };
        s.push('\n');
        let _ = writeln!(s, "# {} (template {})", peer.name, peer.template);
        s.push_str("[Peer]\n");
        let _ = writeln!(s, "PublicKey = {}", w.public_key);
        if let Some(psk) = &w.preshared_key {
            let _ = writeln!(s, "PresharedKey = {}", psk.expose_base64());
        }
        let _ = writeln!(s, "AllowedIPs = {addr}/32");
    }
    Ok(Artifact::secret(
        ArtifactKind::WireGuardServer,
        path(model),
        s,
    ))
}
