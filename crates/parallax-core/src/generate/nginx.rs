//! nginx `allow`/`deny` snippets. L3 rules gate `host:port`, not virtual
//! hosts, so services multiplexed behind one nginx need this L7 help. Works
//! only because VPN→LAN traffic is routed, not masqueraded: nginx sees the
//! real tunnel address.
//!
//! - `snippets/parallax-<template>.conf`: `allow` lines for the tier's
//!   members (the WireGuard pool; one line per Tailscale node). No `deny`, so
//!   the operator composes them.
//! - `snippets/parallax-service-<name>.conf`: for services marked
//!   `nginx_vhost`, every tier that reaches the service plus the service's own
//!   LAN, then `deny all`.

use std::fmt::Write as _;

use super::{Artifact, ArtifactKind};
use crate::model::Template;
use crate::transport::{self, Transport};
use crate::validate::Model;
use crate::Result;

fn allow_lines(
    s: &mut String,
    model: &Model<'_>,
    template: &Template,
    transports: &[Box<dyn Transport>],
) {
    for tr in transports {
        let members = tr.tier_members(model, template);
        if members.is_empty() {
            let _ = writeln!(s, "# {}: no {} members known yet", template.name, tr.kind());
            continue;
        }
        for m in members {
            let _ = writeln!(
                s,
                "allow {};  # {} via {}",
                if m.prefix_len() == 32 {
                    m.addr().to_string()
                } else {
                    m.to_string()
                },
                template.name,
                tr.kind()
            );
        }
    }
}

pub fn render(model: &Model<'_>) -> Result<Vec<Artifact>> {
    let cfg = model.config();
    let transports = transport::all();
    let mut out = Vec::new();
    for t in &cfg.templates {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "# Generated by Parallax: members of template \"{}\". Include in any vhost this tier may use.",
            t.name
        );
        s.push_str("# Tailscale members are listed per node and regenerate as Headscale's inventory changes.\n");
        allow_lines(&mut s, model, t, &transports);
        out.push(Artifact::public(
            ArtifactKind::NginxSnippet,
            format!("nginx/snippets/parallax-{}.conf", t.name),
            s,
        ));
    }
    for svc in cfg.services.iter().filter(|s| s.nginx_vhost) {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "# Generated by Parallax: access list for service \"{}\" ({}:{}). Include in its vhost.",
            svc.name, svc.host, svc.port
        );
        for t in cfg
            .templates
            .iter()
            .filter(|t| model.reaches_service(t, svc))
        {
            allow_lines(&mut s, model, t, &transports);
        }
        if let Some(n) = model.network_containing(svc.host) {
            let _ = writeln!(
                s,
                "allow {};  # network {} (local clients)",
                n.subnet.trunc(),
                n.name
            );
        }
        s.push_str("deny all;\n");
        out.push(Artifact::public(
            ArtifactKind::NginxSnippet,
            format!("nginx/snippets/parallax-service-{}.conf", svc.name),
            s,
        ));
    }
    Ok(out)
}
