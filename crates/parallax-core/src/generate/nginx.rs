//! nginx `allow`/`deny` snippets. L3 rules gate `host:port`, not virtual
//! hosts, so services multiplexed behind one nginx need this L7 help. Works
//! only because VPN→LAN traffic is routed, not masqueraded: nginx sees the
//! real tunnel address.
//!
//! - `snippets/parallax-<grant>.conf`: `allow` lines for every peer that
//!   has the grant (one line per address). No `deny`, so the operator
//!   composes them.
//! - `snippets/parallax-service-<name>.conf`: for services marked
//!   `nginx_vhost`, every tier that reaches the service plus the service's own
//!   LAN, then `deny all`.

use std::fmt::Write as _;

use super::{Artifact, ArtifactKind};
use crate::tier::Tier;
use crate::transport::{self, Transport};
use crate::validate::Model;
use crate::Result;

fn allow_lines(
    s: &mut String,
    model: &Model<'_>,
    tier: &Tier<'_>,
    transports: &[Box<dyn Transport>],
) {
    for tr in transports {
        let members = tr.tier_members(model, tier);
        if members.is_empty() {
            let _ = writeln!(s, "# {}: no {} members known yet", tier.label(), tr.kind());
            continue;
        }
        for m in members {
            let _ = writeln!(
                s,
                "allow {};  # {} via {}",
                if m.prefix_len() == 32 {
                    m.addr().to_string()
                } else {
                    m.to_string()
                },
                tier.label(),
                tr.kind()
            );
        }
    }
}

pub fn render(model: &Model<'_>) -> Result<Vec<Artifact>> {
    let cfg = model.config();
    let transports = transport::all();
    let mut out = Vec::new();
    for g in &cfg.grants {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "# Generated by Parallax: peers with grant \"{}\". Include in any vhost they may use.",
            g.name
        );
        s.push_str("# Tailscale members are listed per node and regenerate as Headscale's inventory changes.\n");
        let tiers: Vec<&Tier<'_>> = model
            .tiers()
            .iter()
            .filter(|t| t.grants.iter().any(|h| h.name == g.name))
            .collect();
        if tiers.is_empty() {
            s.push_str("# No peer has this grant.\n");
        }
        for t in tiers {
            allow_lines(&mut s, model, t, &transports);
        }
        out.push(Artifact::public(
            ArtifactKind::NginxSnippet,
            format!("nginx/snippets/parallax-{}.conf", g.name),
            s,
        ));
    }
    for svc in cfg.services.iter().filter(|s| s.nginx_vhost) {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "# Generated by Parallax: access list for service \"{}\" ({} {}). Include in its vhost.",
            svc.name,
            svc.host,
            svc.ports
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        );
        for t in model
            .tiers()
            .iter()
            .filter(|t| model.reaches_service(t, svc))
        {
            allow_lines(&mut s, model, t, &transports);
        }
        if let Some(n) = model.network_of_host(&svc.host) {
            let _ = writeln!(
                s,
                "allow {};  # network {} (local clients)",
                n.subnet.trunc(),
                n.name
            );
        }
        s.push_str("deny all;\n");
        out.push(Artifact::public(
            ArtifactKind::NginxSnippet,
            format!("nginx/snippets/parallax-service-{}.conf", svc.name),
            s,
        ));
    }
    Ok(out)
}
